# ----------------------------------------------------------------------------- helpers
def load_cfg():
    path = ROOT / "analysis_config.yaml"
    if not path.exists():
        sys.exit(f"Missing {path}. Set up post-analysis first.")
    cfg = yaml.safe_load(path.read_text()) or {}
    cfg["signals"] = cfg.get("signals") or {}
    return cfg


def run_number(p):
    m = re.search(r"_run(\d+)", p.name)
    return int(m.group(1)) if m else -1


def all_runs():
    return sorted((p for p in RUNS.glob("*_run*") if p.is_dir()), key=run_number)


def match_run(token, run):
    return token == run.name or f"_{token}_" in f"{run.name}_"


def resolve_run(arg):
    runs = all_runs()
    if arg == "latest":
        if not runs:
            sys.exit("No runs yet. Start one with: pa.py new <what-changed>")
        return runs[-1]
    hits = [r for r in runs if match_run(arg, r)]
    if len(hits) == 1:
        return hits[0]
    if Path(arg).is_dir():
        return Path(arg).resolve()
    sys.exit(f"Run not found: {arg}")


def lab(name, unit):
    return f"{name} [{unit}]" if unit else name


def fmt(v, col=""):
    if math.isnan(v):
        return "never" if col.endswith("settled_at") else "n/a"
    return f"{v:.4g}"


def save(fig, path):
    fig.savefig(path)
    plt.close(fig)
    print(f"  plot: {path.relative_to(ROOT)}")


# ----------------------------------------------------------------------------- new
def git_info():
    def git(*a):
        try:
            return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, timeout=5).stdout.strip()
        except (OSError, subprocess.SubprocessError):
            return ""
    commit = git("rev-parse", "--short", "HEAD")
    return {"commit": commit or "not a git repo", "dirty": bool(git("status", "--porcelain")) if commit else None}


def cmd_new(args):
    cfg = load_cfg()
    RUNS.mkdir(parents=True, exist_ok=True)
    num = max([run_number(p) for p in all_runs()] + [0]) + 1
    slug = re.sub(r"[^A-Za-z0-9-]+", "-", args.name).strip("-").lower() or "run"
    run = RUNS / f"{dt.date.today():%Y-%m-%d}_run{num:02d}_{slug}"
    (run / "raw").mkdir(parents=True)
    (run / "plots").mkdir()
    meta = {"run_id": run.name, "created": dt.datetime.now().isoformat(timespec="seconds"),
            "what_changed": args.changed or args.name, "baseline": num == 1, "significant": num == 1,
            "verdict": "", "git": git_info(), "notes": ""}
    (run / "run.yaml").write_text(yaml.safe_dump(meta, sort_keys=False))
    rel = os.path.relpath(run, Path.cwd())
    print(f"Created {rel}")
    if cfg.get("source", "ros") == "ros":
        topics = " ".join(sorted({s["topic"] for s in cfg["signals"].values()}))
        ver = str(cfg.get("ros_version", "auto"))
        ver = os.environ.get("ROS_VERSION", "") if ver == "auto" else ver
        if ver in ("", "2"):
            print(f"ROS 2 record:  ros2 bag record -o {rel}/raw/bag {topics}")
        if ver in ("", "1"):
            print(f"ROS 1 record:  rosbag record -O {rel}/raw/run.bag {topics}")
        print("Stop recording with Ctrl+C. Save parameters into the run folder too "
              "(ROS 2: see `ros2 param dump --help`; ROS 1: `rosparam dump <file>`).")
    else:
        print(f"Save this run's CSV log(s) into {rel}/raw/")
    print(f"Then:  python {os.path.relpath(__file__)} analyze {run.name}")


# ----------------------------------------------------------------------------- reading
def quat_yaw(q):
    return math.atan2(2 * (q.w * q.z + q.x * q.y), 1 - 2 * (q.y * q.y + q.z * q.z))


def get_field(obj, path):
    for part in path.split("."):
        m = re.fullmatch(r"(\w+)(?:\[(-?\d+)\])?", part)
        if not m:
            raise ValueError(f"bad field part '{part}'")
        obj = getattr(obj, m.group(1))
        if m.group(2) is not None:
            obj = obj[int(m.group(2))]
    return obj


def to_value(obj, spec):
    tf = spec.get("transform")
    if tf == "yaw":
        obj = quat_yaw(obj)
    elif tf:
        raise ValueError(f"unknown transform '{tf}' (supported: yaw)")
    return float(obj) * float(spec.get("scale", 1.0))


def read_ros(raw, cfg):
    try:
        from rosbags.highlevel import AnyReader
        from rosbags.typesys import Stores, get_typestore, get_types_from_msg
    except ImportError:
        sys.exit("Reading bags needs the 'rosbags' package:  pip install rosbags")
    bags = sorted({p.parent for p in raw.rglob("metadata.yaml")}) + sorted(raw.rglob("*.bag"))
    if not bags:
        sys.exit(f"No bag in {raw}  (ROS 2: a folder with metadata.yaml, written when recording "
                 "stops cleanly with Ctrl+C; ROS 1: a *.bag file)")
    store_name = str(cfg.get("typestore", "LATEST")).upper()
    if store_name not in Stores.__members__:
        sys.exit(f"Unknown typestore '{store_name}'. Options: {', '.join(Stores.__members__)}")
    store = get_typestore(Stores[store_name])
    custom = {}
    for d in cfg.get("msg_dirs") or []:  # custom .msg files, for bags without embedded definitions
        for f in (ROOT / d).resolve().rglob("*.msg"):
            custom.update(get_types_from_msg(f.read_text(), f"{f.parent.parent.name}/msg/{f.stem}"))
    if custom:
        store.register(custom)
    by_topic = {}
    for name, spec in cfg["signals"].items():
        by_topic.setdefault(spec["topic"], []).append((name, spec))
    data = {n: [] for n in cfg["signals"]}
    used = {"header": set(), "receive": set()}
    want_header = cfg.get("time_source", "header") == "header"
    with AnyReader(bags, default_typestore=store) as reader:
        conns = [c for c in reader.connections if c.topic in by_topic]
        missing = set(by_topic) - {c.topic for c in conns}
        if missing:
            print(f"WARNING: topics not in the bag: {', '.join(sorted(missing))}")
        for conn, t_ns, rawdata in reader.messages(connections=conns):
            msg = reader.deserialize(rawdata, conn.msgtype)
            t, src = t_ns * 1e-9, "receive"
            stamp = getattr(getattr(msg, "header", None), "stamp", None)
            if want_header and stamp is not None and (stamp.sec or stamp.nanosec):
                t, src = stamp.sec + stamp.nanosec * 1e-9, "header"
            for name, spec in by_topic[conn.topic]:
                used[src].add(name)
                try:
                    data[name].append((t, to_value(get_field(msg, spec["field"]), spec)))
                except (AttributeError, IndexError, TypeError, ValueError) as e:
                    sys.exit(f"Signal '{name}': cannot read '{spec['field']}' from {conn.msgtype}: {e}\n"
                             "The field must give one number per message (or a quaternion + transform: yaw).")
    if used["header"] and used["receive"] - used["header"]:
        print("WARNING: these signals have no header stamp and use bag receive time: "
              f"{', '.join(sorted(used['receive'] - used['header']))}. If header stamps are sim time, "
              "times will not line up: set time_source: receive, or record with sim time.")
    return data


def read_csv(raw, cfg):
    files = sorted(raw.rglob("*.csv"))
    if not files:
        sys.exit(f"No CSV files in {raw}")
    tables = {}
    for f in files:
        with open(f, newline="") as fh:
            rd = csv.DictReader(fh)
            tables[f] = (rd.fieldnames or [], list(rd))
    data = {}
    for name, spec in cfg["signals"].items():
        col, tcol = spec.get("column", name), spec.get("time_column", cfg.get("csv_time_column", "t"))
        hits = [f for f in files if (not spec.get("file") or f.match(spec["file"]))
                and col in tables[f][0] and tcol in tables[f][0]]
        if not hits:
            print(f"WARNING: no CSV in raw/ has columns '{tcol}' and '{col}' (signal '{name}')")
            continue
        scale = float(spec.get("scale", 1.0))
        data[name] = [(float(r[tcol]), float(r[col]) * scale) for r in tables[hits[0]][1]
                      if r.get(col) not in ("", None) and r.get(tcol) not in ("", None)]
    return data


def to_arrays(data):
    out = {}
    for n, pts in data.items():
        if not pts:
            print(f"WARNING: no data for signal '{n}'")
            continue
        a = np.array(pts, dtype=float)
        a = a[np.argsort(a[:, 0], kind="stable")]
        out[n] = (a[:, 0], a[:, 1])
    return out


# ----------------------------------------------------------------------------- analysis
def align(exp, act, mode):
    """Evaluate expected at the actual timestamps. hold = last setpoint (step), linear = interpolate."""
    (te, ve), (ta, va) = exp, act
    keep = ta >= te[0]
    if mode == "linear":
        keep &= ta <= te[-1]
    t, a = ta[keep], va[keep]
    e = np.interp(t, te, ve) if mode == "linear" else ve[np.searchsorted(te, t, side="right") - 1]
    return t, e, a


def err_metrics(item, t, err, unit, tol=None):
    ae = np.abs(err)
    rows = [(item, "rmse", float(np.sqrt(np.mean(err ** 2))), unit),
            (item, "mean_abs", float(ae.mean()), unit),
            (item, "max_abs", float(ae.max()), unit),
            (item, "final_abs", float(ae[int(len(ae) * 0.9):].mean()), unit)]  # mean |error|, last 10 %
    if tol is not None:
        out = np.nonzero(ae > tol)[0]
        settled = t[0] if len(out) == 0 else (t[out[-1] + 1] if out[-1] + 1 < len(t) else float("nan"))
        rows.append((item, "settled_at", float(settled), "s"))  # run time after which |error| <= tol
    return rows


def analyze_pair(run_id, p, sig, out):
    name, unit, mode = p["name"], p.get("unit", ""), p.get("expected_interp", "hold")
    if p["expected"] not in sig or p["actual"] not in sig:
        print(f"WARNING: pair '{name}' skipped (missing signal data)")
        return []
    t, e, a = align(sig[p["expected"]], sig[p["actual"]], mode)
    if len(t) < 2:
        print(f"WARNING: pair '{name}' skipped (expected and actual do not overlap in time)")
        return []
    err = e - a  # error = expected - actual
    if p.get("angle"):
        err = (err + math.pi) % (2 * math.pi) - math.pi
    tol = p.get("settle_tol")
    rows = err_metrics(name, t, err, unit, tol)
    m = {r[1]: r[2] for r in rows}
    fig, (ax1, ax2) = plt.subplots(2, 1, sharex=True, figsize=(9, 5.6), gridspec_kw={"height_ratios": [2, 1]})
    te, ve = sig[p["expected"]]
    ta, va = sig[p["actual"]]
    if mode == "hold" and ta[-1] > te[-1]:  # a setpoint stays valid until the end
        te, ve = np.append(te, ta[-1]), np.append(ve, ve[-1])
    ax1.plot(te, ve, color=EXP, ls="--", drawstyle="steps-post" if mode == "hold" else "default",
             label=f"expected ({p['expected']})")
    ax1.plot(ta, va, color=ACT, label=f"actual ({p['actual']})")
    ax1.set_ylabel(lab(name, unit))
    ax1.legend(loc="best")
    ax1.set_title(f"{name}: expected vs actual   |   RMSE {m['rmse']:.3g} {unit}   max {m['max_abs']:.3g} {unit}",
                  loc="left")
    ax2.plot(t, err, color=ACT, label="error = expected - actual")
    ax2.axhline(0, color=MUTED, lw=0.8)
    if tol is not None:
        ax2.axhspan(-tol, tol, color=GRID, lw=0, label=f"±{tol} {unit} tolerance")
        if not math.isnan(m["settled_at"]):
            ax2.axvline(m["settled_at"], color=MUTED, ls=":", lw=1.2, label=f"settled at {m['settled_at']:.2f} s")
    ax2.legend(loc="best", fontsize=8)
    ax2.set_ylabel(lab("error", unit))
    ax2.set_xlabel("time [s]")
    fig.suptitle(run_id, x=0.01, ha="left", color=MUTED, fontsize=9)
    save(fig, out / f"pair_{name}.png")
    return rows


def analyze_path(run_id, p, sig, out):
    name, unit = p["name"], p.get("unit", "")
    (ex, ey), (ax_, ay) = p["expected"], p["actual"]
    if not all(s in sig for s in (ex, ey, ax_, ay)):
        print(f"WARNING: path '{name}' skipped (missing signal data)")
        return []
    tax, vax = sig[ax_]
    vay = np.interp(tax, *sig[ay])  # actual y on actual x timestamps
    pex, pey = sig[ex][1], np.interp(sig[ex][0], *sig[ey])
    if p.get("match", "time") == "nearest":  # distance to the expected path line (fixed path, cross-track)
        P, A = np.column_stack([pex, pey]), np.column_stack([vax, vay])
        S0, S1 = (P[:-1], P[1:]) if len(P) > 1 else (P, P)
        seg = S1 - S0
        L2 = np.where((seg ** 2).sum(1) > 0, (seg ** 2).sum(1), 1.0)
        step, parts = max(1, 2_000_000 // len(S0)), []
        for i in range(0, len(A), step):
            rel = A[i:i + step, None] - S0[None]
            u = np.clip((rel * seg[None]).sum(2) / L2, 0, 1)
            parts.append(np.linalg.norm(rel - u[..., None] * seg[None], axis=2).min(axis=1))
        d, t = np.concatenate(parts), tax
    else:  # same-time distance (moving target)
        mode = p.get("expected_interp", "hold")
        t, exv, axv = align(sig[ex], (tax, vax), mode)
        _, eyv, ayv = align((sig[ex][0], pey), (tax, vay), mode)
        d = np.hypot(exv - axv, eyv - ayv)
    if len(d) < 2:
        print(f"WARNING: path '{name}' skipped (no overlap)")
        return []
    rows = err_metrics(name, t, d, unit)
    m = {r[1]: r[2] for r in rows}
    fig, ax = plt.subplots(figsize=(6.8, 6.4))
    ax.plot(pex, pey, color=EXP, ls="--", marker="o" if len(pex) < 60 else None, ms=4, label=f"expected ({ex}, {ey})")
    ax.plot(vax, vay, color=ACT, label=f"actual ({ax_}, {ay})")
    ax.plot(vax[0], vay[0], "o", color=INK, ms=7, label="start")
    ax.plot(vax[-1], vay[-1], "s", color=INK, ms=7, label="end")
    ax.set_aspect("equal", adjustable="datalim")
    ax.set_xlabel(lab("x", unit))
    ax.set_ylabel(lab("y", unit))
    ax.set_title(f"{name}: path ({p.get('match', 'time')} match)   |   RMSE {m['rmse']:.3g} {unit}   "
                 f"max {m['max_abs']:.3g} {unit}", loc="left")
    ax.legend(loc="best", fontsize=8)
    fig.suptitle(run_id, x=0.01, ha="left", color=MUTED, fontsize=9)
    save(fig, out / f"path_{name}.png")
    return rows


def plot_signals(run_id, names, sig, units, out):
    names = [n for n in names if n in sig]
    if not names:
        return
    fig, axes = plt.subplots(len(names), 1, sharex=True, figsize=(9, 1.9 * len(names) + 0.9), squeeze=False)
    for ax, n in zip(axes[:, 0], names):
        ax.plot(*sig[n], color=ACT)
        ax.set_ylabel(lab(n, units.get(n, "")))
    axes[0, 0].set_title("key signals", loc="left")
    axes[-1, 0].set_xlabel("time [s]")
    fig.suptitle(run_id, x=0.01, ha="left", color=MUTED, fontsize=9)
    save(fig, out / "signals.png")


def cmd_analyze(args):
    cfg = load_cfg()
    run = resolve_run(args.run)
    print(f"Analyzing {run.name}")
    data = read_ros(run / "raw", cfg) if cfg.get("source", "ros") == "ros" else read_csv(run / "raw", cfg)
    sig = to_arrays(data)
    if not sig:
        sys.exit("No data extracted. Check the signals in analysis_config.yaml.")
    t0 = min(t[0] for t, _ in sig.values())
    sig = {n: (t - t0, v) for n, (t, v) in sig.items()}  # time 0 = first sample of the run
    units = {n: (s or {}).get("unit", "") for n, s in cfg["signals"].items()}
    with open(run / "data.csv", "w", newline="") as f:  # tidy copy of every signal, for re-plotting
        w = csv.writer(f)
        w.writerow(["signal", "t", "value", "unit"])
        for n, (t, v) in sig.items():
            w.writerows([n, f"{ti:.6f}", f"{vi:.9g}", units.get(n, "")] for ti, vi in zip(t, v))
    (run / "plots").mkdir(exist_ok=True)
    rows = []
    for p in cfg.get("pairs") or []:
        rows += analyze_pair(run.name, p, sig, run / "plots")
    for p in cfg.get("paths") or []:
        rows += analyze_path(run.name, p, sig, run / "plots")
    plot_signals(run.name, cfg.get("plots") or [], sig, units, run / "plots")
    with open(run / "metrics.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["item", "metric", "value", "unit"])
        w.writerows((i, k, f"{v:.6g}", u) for i, k, v, u in rows)
    print("\n  item          metric        value")
    for i, k, v, u in rows:
        print(f"  {i:<13} {k:<13} {v:.4g} {u}")
    print(f"\nWrote {(run / 'metrics.csv').relative_to(ROOT)}. Look at the plots, then fill "
          "what_changed / verdict / significant in run.yaml.")


# ----------------------------------------------------------------------------- compare
def cmd_compare(args):
    cfg = load_cfg()
    picked = []
    for r in all_runs():
        meta = yaml.safe_load((r / "run.yaml").read_text()) if (r / "run.yaml").exists() else {}
        meta = meta or {}
        if args.all:
            want = True
        elif args.runs:
            want = any(match_run(tok, r) for tok in args.runs)
        else:
            want = bool(meta.get("significant") or meta.get("baseline"))
        if not want:
            continue
        if not (r / "metrics.csv").exists():
            print(f"WARNING: {r.name} has no metrics.csv yet (run: pa.py analyze {r.name})")
            continue
        with open(r / "metrics.csv", newline="") as f:
            mets = {f"{row['item']}.{row['metric']}": (float(row["value"]), row["unit"]) for row in csv.DictReader(f)}
        picked.append((r, meta, mets))
    if not picked:
        sys.exit("No runs selected. Set significant: true in a run's run.yaml, or use --all / --runs.")
    cols = cfg.get("compare_columns")
    if not cols:
        cols = []
        for _, _, mets in picked:
            for key in mets:
                item, metric = key.rsplit(".", 1)
                for c in (f"{item}.rmse", f"{item}.max_abs"):
                    if metric in ("rmse", "max_abs") and c not in cols:
                        cols.append(c)
    units = {c: next((m[c][1] for _, _, m in picked if c in m), "") for c in cols}
    base = next(((r, m) for r, meta, m in picked if meta.get("baseline")), None)
    head = ["Run", "What changed"] + [lab(c, units[c]) for c in cols]
    if base and cols:
        head.append(f"Δ {cols[0]} vs baseline")
    head += ["Verdict", "Plots"]
    md = ["# Run comparison", "", f"Generated {dt.datetime.now():%Y-%m-%d %H:%M} by pa.py compare. "
          "Errors: lower is better. Δ is the change against the baseline run.", "",
          "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    csv_rows = []
    for r, meta, mets in picked:
        vals = [mets[c][0] if c in mets else float("nan") for c in cols]
        cells = [r.name + (" (baseline)" if meta.get("baseline") else ""), str(meta.get("what_changed", ""))]
        cells += [fmt(v, c) for v, c in zip(vals, cols)]
        if base and cols:
            b = base[1].get(cols[0], (float("nan"),))[0]
            bad = r == base[0] or not b or math.isnan(b) or math.isnan(vals[0])
            cells.append("-" if bad else f"{(vals[0] - b) / abs(b) * 100:+.1f} %")
        cells += [str(meta.get("verdict", "")), f"[plots](runs/{r.name}/plots)"]
        md.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
        csv_rows.append([r.name, meta.get("what_changed", ""), meta.get("baseline", False),
                         meta.get("significant", False), meta.get("verdict", "")] + vals)
    md += ["", "![comparison](comparison.png)", ""]
    (ROOT / "comparison.md").write_text("\n".join(md))
    with open(ROOT / "comparison.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["run_id", "what_changed", "baseline", "significant", "verdict"] + cols)
        w.writerows(csv_rows)
    show = cols[:4]
    if show:
        names = [r.name.split("_", 1)[1] + (" (baseline)" if meta.get("baseline") else "") for r, meta, _ in picked]
        fig, axes = plt.subplots(1, len(show), figsize=(3.6 * len(show) + 1.8, 0.45 * len(picked) + 1.6),
                                 sharey=True, squeeze=False)
        for ax, c in zip(axes[0], show):
            vals = [m.get(c, (float("nan"),))[0] for _, _, m in picked]
            y = np.arange(len(vals))[::-1]
            ax.barh(y, np.nan_to_num(vals), color=ACT, height=0.6)
            for yi, v in zip(y, vals):
                ax.text(0 if math.isnan(v) else v, yi, f" {fmt(v, c)}", va="center", fontsize=8,
                        color=MUTED if math.isnan(v) else INK)
            ax.set_yticks(y)
            ax.set_yticklabels(names)
            ax.set_xlabel(lab(c, units[c]))
            ax.grid(axis="y", visible=False)
            ax.margins(x=0.25)
        axes[0, 0].set_title("run comparison (lower is better)", loc="left")
